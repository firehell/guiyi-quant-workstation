import { expect, test } from '@playwright/test'
import { mockMarketDetail } from './market-detail.helpers.mjs'

test('saved chart keeps one price canvas through pane selection, order, resizing and strategy changes', async ({page}) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await mockMarketDetail(page)
  await page.goto('/market/chart?view=newow&newow_source=after-market&symbol=jm&series_kind=actual_dominant&frequency=15m')
  const shell = page.getByTestId('kline-shell')
  const panes = shell.locator('[data-workstation-pane]')
  await expect(panes).toHaveCount(1)
  await expect(panes.first()).toContainText('历史回看，会重绘')
  await shell.locator('canvas').first().evaluate(canvas => { window.workstationPriceCanvas = canvas })
  await page.getByRole('button', { name: '指标库 I' }).click()
  const settings = page.locator('.workstation-chart-settings')
  await settings.locator('summary').click()
  await settings.getByLabel('EMA21').check()
  await settings.getByLabel('调整线条').selectOption('ema_21')
  await settings.getByLabel('线宽').selectOption('4')
  await settings.getByLabel('颜色').fill('#308951')
  await settings.getByLabel('主图对数价格轴').check()
  await settings.getByRole('button',{name:'添加副图'}).click()
  await settings.getByRole('button',{name:'添加副图'}).click()
  await expect(panes).toHaveCount(3)
  await expect(settings.getByRole('button',{name:'添加副图'})).toBeDisabled()
  await settings.getByLabel('副图 2 指标').selectOption('macd')
  await expect(panes.nth(1)).toContainText('MACD')
  await settings.getByRole('button',{name:'上移'}).nth(1).click()
  await expect(panes.first()).toContainText('MACD')
  await settings.getByLabel('高度').first().selectOption('200')
  await settings.getByRole('button',{name:'移除'}).last().click()
  await expect(panes).toHaveCount(2)
  await page.getByRole('button',{name:'震荡',exact:true}).click()
  await expect(page).toHaveURL(/strategy=oscillation/)
  await expect(panes).toHaveCount(1)
  await expect(panes.first()).toContainText('历史回看，会重绘')
  expect(await shell.locator('canvas').first().evaluate(canvas => window.workstationPriceCanvas === canvas)).toBe(true)
  const quick = page.getByRole('group',{name:'切换首个副图'})
  await quick.getByRole('button',{name:'主力控盘'}).click()
  await expect(panes.first()).toContainText('主力控盘')
  const enlarge = panes.first().getByRole('button', { name: '放大主力控盘' })
  await enlarge.click()
  await expect(panes.first().getByRole('button', { name: '还原主力控盘' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button',{name:'趋势',exact:true}).click()
  await expect(panes).toHaveCount(2)
  await expect(panes.first()).toContainText('MACD')
  await page.getByRole('button',{name:'震荡',exact:true}).click()
  await expect(panes).toHaveCount(1)
  await expect(panes.first()).toContainText('主力控盘')
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('guiyi.workstation.chart.layers.v1')))
  expect(persisted.strokes.ema_21).toEqual({color:'#308951', lineWidth:4})
  expect(persisted.logPrice).toBe(true)
  expect(errors).toEqual([])
})
