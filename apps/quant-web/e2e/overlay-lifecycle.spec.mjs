import { test, expect } from '@playwright/test'
for (const kind of ['facts', 'newow']) {
  test(`${kind}: close/reopen, Escape, identity and unmount`, async ({ page }) => {
    await page.goto('/e2e/fixtures/overlay-lifecycle.html')
    await page.evaluate(kind => { window.overlayHarness.state.kind = kind }, kind)
    await page.locator('#opener').click()
    const dialog = page.locator('dialog')
    await expect(dialog).toBeVisible()
    await page.evaluate(() => window.overlayHarness.reopen())
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    await expect(dialog).toBeVisible()
    expect(await page.evaluate(() => window.overlayHarness.state.closes)).toBe(0)
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(page.locator('#opener')).toBeFocused()
    await page.locator('#opener').click()
    await page.evaluate(() => { window.overlayHarness.state.identity = 'B' })
    await expect(dialog).not.toBeVisible()
    expect(await page.evaluate(() => window.overlayHarness.state.open)).toBe(false)
    await page.locator('#opener').click()
    await expect(dialog).toBeVisible()
    await page.evaluate(() => { window.overlayHarness.state.mounted = false })
    await expect(dialog).toHaveCount(0)
    await expect(page.locator('#opener')).toBeFocused()
    expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
  })
  test(`${kind}: nested locks, focus, 390px`, async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e/fixtures/overlay-lifecycle.html')
    await page.evaluate(kind => { window.overlayHarness.state.kind = kind; document.body.style.overflow = 'auto' }, kind)
    await page.locator('#drawer-opener').click()
    await expect(page.getByRole('button', { name: '关闭', exact: true })).toBeFocused()
    await page.locator('#nested-opener').click()
    const dialog = page.locator('dialog')
    await expect(dialog).toBeVisible()
    const bounds = await dialog.boundingBox()
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(390)
    await page.locator('#last-action').focus()
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(page.locator('#nested-opener')).toBeFocused()
    expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
    await expect(page.getByRole('dialog', { name: '历史' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog', { name: '历史' })).toHaveCount(0)
    await expect(page.locator('#drawer-opener')).toBeFocused()
    expect(await page.evaluate(() => document.body.style.overflow)).toBe('auto')
  })
}
test('lower drawer close retains upper dialog lock', async ({ page }) => {
  await page.goto('/e2e/fixtures/overlay-lifecycle.html')
  await page.locator('#drawer-opener').click()
  await page.locator('#nested-opener').click()
  await expect(page.locator('dialog')).toBeVisible()
  await page.evaluate(() => { window.overlayHarness.state.drawer = false })
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.keyboard.press('Escape')
  await expect(page.locator('dialog')).not.toBeVisible()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})

for (const kind of ['facts', 'newow']) {
  test(`${kind}: backdrop and direct native close synchronize controlled state`, async ({ page }) => {
    await page.goto('/e2e/fixtures/overlay-lifecycle.html')
    await page.evaluate(kind => { window.overlayHarness.state.kind = kind }, kind)
    await page.locator('#opener').click()
    await expect(page.locator('dialog')).toBeVisible()
    await page.mouse.click(1, 1)
    await expect(page.locator('dialog')).not.toBeVisible()
    await expect(page.locator('#opener')).toBeFocused()
    await page.locator('#opener').click()
    await page.locator('dialog').evaluate(dialog => dialog.close())
    await expect.poll(() => page.evaluate(() => window.overlayHarness.state.open)).toBe(false)
    await expect(page.locator('#opener')).toBeFocused()
  })
}
test('drawer close and unmount restore focus and release scroll', async ({ page }) => {
  await page.goto('/e2e/fixtures/overlay-lifecycle.html')
  await page.locator('#drawer-opener').click()
  await page.evaluate(() => { window.overlayHarness.state.drawer = false })
  await expect(page.locator('#drawer-opener')).toBeFocused()
  await page.locator('#drawer-opener').click()
  await page.evaluate(() => { window.overlayHarness.state.drawerMounted = false })
  await expect(page.getByRole('dialog', { name: '历史' })).toHaveCount(0)
  await expect(page.locator('#drawer-opener')).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})
for (const variant of ['niuwa-indicator', 'ai-analysis']) {
  test(`Newow ${variant} preserves skin at 390px`, async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e/fixtures/overlay-lifecycle.html')
    await page.evaluate(variant => { Object.assign(window.overlayHarness.state, { kind: 'newow', variant }) }, variant)
    await page.locator('#opener').click()
    const dialog = page.locator('dialog')
    await expect(dialog).toBeVisible()
    await expect(dialog).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(dialog).toHaveCSS('border-top-left-radius', variant === 'ai-analysis' ? '16px' : '22px')
    const bounds = await dialog.boundingBox()
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(390)
    await page.getByRole('button', { name: '知道了' }).click()
    await expect(dialog).not.toBeVisible()
  })
}
