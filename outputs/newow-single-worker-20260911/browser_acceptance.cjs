const {chromium,expect}=require('../../apps/quant-web/node_modules/@playwright/test');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const records=[],pending=[],errors=[];
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.url().includes('/newow/strategy-detail'))pending.push((async()=>{
   const b=await r.json();records.push({params:Object.fromEntries(new URL(r.url()).searchParams),status:r.status(),body:b});
  })())});
  await page.goto('http://127.0.0.1:5174/market/chart?symbol=au&view=newow&strategy=trend&frequency=1d&series_kind=actual_dominant');
  await expect(page.locator('[data-detail-workspace="newow"]')).toHaveAttribute('data-chart-state','ready',{timeout:120000});
  await page.locator('.newow-reference').scrollIntoViewIfNeeded();
  await page.getByTestId('newow-reference-summary').waitFor({timeout:120000});
  await expect(page.getByTestId('newow-reference-summary')).toContainText('56');
  const beforeCount=await page.getByRole('button',{name:/定位参考记录/}).count();
  const more=page.waitForResponse(r=>r.url().includes('history_before=')&&r.url().includes('/newow/strategy-detail'));
  await page.getByRole('button',{name:'加载更多参考历史',exact:true}).click();
  const moreResponse=await more;expect(moreResponse.status()).toBe(200);
  await expect.poll(()=>page.getByRole('button',{name:/定位参考记录/}).count()).toBeGreaterThan(beforeCount);
  const afterCount=await page.getByRole('button',{name:/定位参考记录/}).count();
  const aux=page.waitForResponse(r=>r.url().includes('component=zhaoyao_mirror'));
  await page.getByRole('button',{name:'照妖镜',exact:true}).click();
  expect((await aux).status()).toBe(200);
  await expect(page.getByTestId('newow-product-chart-stage')).toHaveAttribute('data-auxiliary-state','ready',{timeout:30000});
  const earlier=page.waitForResponse(r=>r.url().includes('chart_older_window='));
  await page.getByTestId('newow-load-earlier').click();
  const earlierResponse=await earlier;expect(earlierResponse.status()).toBe(200);
  const earlierBody=await earlierResponse.json();
  if(earlierBody.chart.value.next_older_window) await expect(page.getByTestId('newow-load-earlier')).toBeEnabled({timeout:30000});
  else await expect(page.getByTestId('newow-load-earlier')).toHaveCount(0);
  await expect(page.locator('[data-detail-workspace="newow"]')).toHaveAttribute('data-chart-state','ready');
  const locateButton=page.getByRole('button',{name:/定位参考记录/}).last();
  const locatedId=(await locateButton.getAttribute('aria-label')).split(' ')[1];
  await locateButton.click();
  const lastTrade=(await moreResponse.json()).reference.value.items.at(-1);
  await expect(page.getByTestId('newow-product-chart-stage')).toHaveAttribute('data-selected-signal-id',lastTrade.entry_signal_id,{timeout:30000});
  await expect(page.locator('.newow-reference')).toContainText('已按精确信号 '+lastTrade.entry_signal_id);
  const selectedRow=page.locator('.newow-reference__card[data-selected="true"]');
  await expect(selectedRow.getByRole('button',{name:new RegExp('定位参考记录 '+locatedId)})).toHaveCount(1);
  await expect(page.getByTestId('newow-reference-summary')).toContainText('56');
  await page.getByTestId('newow-product-chart-stage').scrollIntoViewIfNeeded();
  await page.screenshot({path:'.run/single-worker/browser-chart.png'});
  await page.locator('.newow-reference').scrollIntoViewIfNeeded();
  await page.screenshot({path:'.run/single-worker/browser-reference.png'});
  await Promise.all(pending);
  expect(errors).toEqual([]);
  expect(records.every(x=>x.status===200)).toBe(true);
  const tokens=[...new Set(records.map(x=>x.body.meta.snapshot_token))];expect(tokens.length).toBe(1);expect(tokens[0]).toBeTruthy();
  const refs=records.filter(x=>x.params.section==='reference');
  expect(refs.length).toBeGreaterThanOrEqual(2);
  expect(refs.every(x=>JSON.stringify(x.body.reference.value.summary)===JSON.stringify(refs[0].body.reference.value.summary))).toBe(true);
  const trace=records.map(x=>({params:x.params,status:x.status,token:x.body.meta.snapshot_token,input_sha256:x.body.meta.input_content_sha256,section_status:x.body[x.body.section]?.status}));
  const report={code_sha:'044972b82201afe6dc9ee5a532040d748b862bac',product:'au',cutoff:'2026-09-08T07:00:00.000001Z',mode:'actual_candidate_no_route_interception',before_reference_count:beforeCount,after_reference_count:afterCount,located_reference_id:locatedId,page_errors:errors,all_status_200:true,one_snapshot_token:true,reference_summary_unchanged:true,trace};
  fs.writeFileSync('.run/single-worker/browser-acceptance.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify({...report,trace:trace.map(x=>({section:x.params.section||'chart',status:x.status,history_page:!!x.params.history_before,chart_page:!!x.params.chart_older_window}))},null,2));
 }finally{await browser.close()}
})().catch(e=>{console.error(e.message);process.exit(1)});
