import { expect, test } from '@playwright/test'
import { installNewowProductFixtures, newowRoute, assertNoUnexpectedRequests, productRequests } from './newow-product.helpers.mjs'

for (const width of [1440, 390]) {
  test(`nine UI items: display controls, exact facts, formulas and dual tracks at ${width}`, async ({ page }) => {
    const fixture = await installNewowProductFixtures(page, { dualMarket: true })
    await page.setViewportSize({ width, height: 900 })
    await page.goto(newowRoute())
    const stage = page.getByTestId('newow-product-chart-stage')
    await expect(stage).toHaveAttribute('data-auxiliary-state', 'ready')
    const action = stage.locator('[data-action-id]').first()
    const id = await action.getAttribute('data-action-id')
    await expect(action).toHaveAttribute('title', new RegExp(id))
    await expect(action).toHaveAttribute('data-reference-contract', 'RB2605')
    await expect(stage.locator('[data-reference-price="109.3061"]')).toHaveCount(1)
    await stage.locator('.newow-product-chart-stage__main-legend').click()
    await expect(page.getByRole('dialog')).toContainText('尚未开放跨周期综合解释')
    await page.getByRole('button', { name: '知道了', exact: true }).click()
    await stage.getByRole('button', { name: '简洁标记', exact: true }).click()
    await expect(stage.locator('[data-action-id]')).toHaveCount(0)
    await stage.getByRole('button', { name: '详细标记', exact: true }).click()
    await stage.locator('.newow-product-chart-stage__layers summary').click()
    await stage.getByRole('button', { name: '建仓 / 清仓', exact: true }).click()
    await expect(stage.locator('[data-action-id]')).toHaveCount(0)
    await stage.getByRole('button', { name: '建仓 / 清仓', exact: true }).click()
    await stage.locator('.newow-product-chart-stage__layers summary').click()
    await stage.getByRole('button', { name: '双策略对照', exact: true }).click()
    await expect(stage).toHaveAttribute('data-comparison-active', 'true')
    expect(productRequests(fixture, 'chart').filter(item => item.strategy === 'oscillation')).toHaveLength(1)
    const osc = stage.locator('[data-origin-strategy="oscillation"]').first()
    await expect(osc).toHaveAttribute('data-action-id', /.+/)
    await stage.locator('.newow-product-chart-stage__dual-controls details summary').click()
    await stage.getByRole('button', { name: '趋势标记', exact: true }).click()
    await expect(stage.locator('[data-origin-strategy="trend"]')).toHaveCount(0)
    await expect(stage.locator('[data-origin-strategy="oscillation"]').first()).toBeVisible()
    await stage.getByRole('button', { name: '趋势标记', exact: true }).click()
    await stage.getByRole('button', { name: '背景着色', exact: true }).click()
    await expect(stage.getByRole('button', { name: '背景着色', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await stage.getByRole('button', { name: '简', exact: true }).click()
    await expect(stage.locator('[data-origin-strategy="oscillation"]').first()).toBeVisible()
    await expect(stage.getByRole('button', { name: '简', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(stage.getByRole('button', { name: '详', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await expect(osc.locator('strong')).toHaveText(/^(建仓|清仓) \d+\.\d{2}$/)
    await expect(osc.locator('span')).toHaveCount(0)
    const compactText = await osc.innerText()
    await stage.getByRole('button', { name: '详', exact: true }).click()
    await expect(stage.getByRole('button', { name: '详', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(osc.locator('span')).toHaveCount(1)
    expect(await osc.innerText()).not.toBe(compactText)
    await stage.getByRole('button', { name: '双策略对照', exact: true }).click()
    await expect(stage).toHaveAttribute('data-comparison-active', 'false')
    await expect(stage.locator('.newow-product-chart-stage__action-callouts:not(.newow-product-chart-stage__dual-tracks) [data-action-id]').first()).toBeVisible()
    await stage.getByRole('button', { name: '双策略对照', exact: true }).click()
    await expect(stage).toHaveAttribute('data-comparison-active', 'true')
    await page.screenshot({ path: `/private/tmp/newow-ui-nine-dual-${width}.png`, fullPage: false })
    const nativeRows = stage.locator('tr').filter({ has: page.locator('td:nth-child(3)') })
    await expect(nativeRows).toHaveCount(4)
    await expect.poll(async () => {
      const auxPane = await nativeRows.nth(2).boundingBox()
      const toolbar = await stage.locator('.newow-product-chart-stage__auxiliary-toolbar').boundingBox()
      return Math.abs(auxPane.y - toolbar.y)
    }).toBeLessThanOrEqual(4)
    await page.locator('.newow-product-workspace__auxiliary-tabs details summary').click()
    await page.getByRole('button', { name: '公式速查', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toContainText('A=MAp(T,7)')
    await dialog.getByRole('combobox', { name: '公式速查主题' }).selectOption('trend_reversal')
    await expect(dialog).toContainText('WR1>97')
    await page.screenshot({ path: `/private/tmp/newow-ui-nine-formula-${width}.png` })
    await page.keyboard.press('Escape')
    const disclosure = page.locator('details.newow-reference__raw-facts')
    await disclosure.locator('summary').click()
    await expect(disclosure).toHaveAttribute('open', '')
    await expect(page.locator('.newow-reference__cards [data-reference-category]')).toHaveCount(2)
    await expect(page.getByRole('button', { name: '全部', exact: true })).toBeVisible()
    await page.screenshot({ path: `/private/tmp/newow-ui-nine-reference-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    assertNoUnexpectedRequests(fixture)
  })
}

test('incompatible companion fails closed while single-strategy facts remain readable', async ({ page }) => {
  const fixture = await installNewowProductFixtures(page)
  await page.goto(newowRoute())
  const stage = page.getByTestId('newow-product-chart-stage')
  await expect(stage).toHaveAttribute('data-auxiliary-state', 'ready')
  await stage.getByRole('button', { name: '双策略对照', exact: true }).click()
  await expect(page.getByText('两策略的窗口、时间或物理合约事实无法对齐，已停止叠加。')).toBeVisible()
  await expect(stage).toHaveAttribute('data-comparison-active', 'false')
  await expect(stage.locator('[data-action-id]').first()).toBeVisible()
  assertNoUnexpectedRequests(fixture)
})

test('chart price row owns the only period selector and preserves daily-weekly navigation', async ({ page }) => {
  const fixture = await installNewowProductFixtures(page, { weeklyCandidate: true })
  await page.goto(newowRoute())
  const row = page.getByLabel('主图参考价格', { exact: true })
  await expect(row.getByRole('group', { name: '周期', exact: true })).toBeVisible()
  await expect(page.locator('.detail-view-nav').getByRole('group', { name: '周期', exact: true })).toHaveCount(0)
  await expect(row.getByRole('button', { name: '1d', exact: true })).toHaveText('日K')
  await row.getByRole('button', { name: '1w', exact: true }).click()
  await expect(page.getByTestId('newow-product-chart-stage')).toHaveAttribute('data-frequency', '1w')
  await expect(row.getByRole('button', { name: '1w', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await row.getByRole('button', { name: '1d', exact: true }).click()
  await expect(page.getByTestId('newow-product-chart-stage')).toHaveAttribute('data-frequency', '1d')
  assertNoUnexpectedRequests(fixture)
})
