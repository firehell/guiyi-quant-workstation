import { expect, test } from '@playwright/test'
import { installNewowProductFixtures, newowRoute, productRequests, assertNoUnexpectedRequests } from './newow-product.helpers.mjs'
for (const width of [1440, 390]) {
  test(`closed curve keeps its totals while raw records page at ${width}`, async ({ page }) => {
    const fixture = await installNewowProductFixtures(page, { recordsHistory: true })
    await page.setViewportSize({ width, height: 900 })
    await page.goto(newowRoute())
    const disclosure = page.locator('details.newow-reference__raw-facts')
    await expect(disclosure).not.toHaveAttribute('open', '')
    await disclosure.locator('summary').click()
    await expect(disclosure).toHaveAttribute('open', '')
    const curve = page.getByLabel('已完成参考交易累计收益曲线', { exact: true })
    await expect(page.getByTestId('newow-reference-summary')).toBeVisible()
    await expect(curve.locator('circle')).toHaveCount(2)
    const points = await curve.locator('polyline').evaluateAll(nodes => nodes.map(node => node.getAttribute('points')))
    expect(points).toHaveLength(2)
    await expect(page.locator('.newow-reference__cards [data-reference-category]')).toHaveCount(2)
    await page.getByRole('button', { name: '加载更多参考历史', exact: true }).click()
    await expect(page.locator('.newow-reference__cards [data-reference-category]')).toHaveCount(4)
    expect(await curve.locator('polyline').evaluateAll(nodes => nodes.map(node => node.getAttribute('points')))).toEqual(points)
    await page.getByRole('button', { name: /2026-06-30，累计 .*定位参考交易/ }).press('Enter')
    await expect(page.locator('#reference-trade-trend-1d-initial')).toBeVisible()
    await expect(curve).toBeVisible()
    await expect(page.locator('.newow-reference__cards [data-reference-category="closed"]')).toHaveCount(2)
    await expect(page.locator('#reference-trade-trend-1d-closed')).toContainText('109.31')
    await expect(page.locator('#reference-trade-trend-1d-initial')).toContainText('RB2601')
    expect(productRequests(fixture, 'reference').filter(item => item.url.searchParams.has('history_limit'))).toHaveLength(2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `/private/tmp/newow-reference-curve-${width}.png`, fullPage: false })
    assertNoUnexpectedRequests(fixture)
  })
}
