import { expect, test } from '@playwright/test'
import { installNewowProductFixtures, newowRoute, assertNoUnexpectedRequests, productRequests } from './newow-product.helpers.mjs'

for (const width of [1440, 390]) {
  test(`nine UI items: display controls, exact facts, formulas and dual tracks at ${width}`, async ({ page }) => {
    const fixture = await installNewowProductFixtures(page, { dualMarket: true })
    await page.setViewportSize({ width, height: 900 })
    await page.goto(newowRoute())
    const stage = page.getByTestId('newow-product-chart-stage')
    await expect(stage).toHaveAttribute('data-auxiliary-state', 'ready')
    const action = stage.locator('[data-action-id]').first()
    const id = await action.getAttribute('data-action-id')
    await expect(action).toHaveAttribute('title', new RegExp(id))
    await expect(action).toHaveAttribute('data-reference-contract', 'RB2605')
    await expect(stage.locator('[data-reference-price="109.3061"]')).toHaveCount(1)
    const settings = stage.getByRole('button', { name: '图表设置', exact: true })
    const drawer = page.getByRole('dialog', { name: '图表设置', exact: true })
    const pure = drawer.getByRole('checkbox', { name: '纯净模式' })
    const extrema = drawer.getByRole('checkbox', { name: '高低点标注（±10）' })
    const nine = drawer.getByRole('checkbox', { name: '九转序列' })
    const actions = drawer.getByRole('checkbox', { name: '建仓 / 清仓' })
    await expect(settings).toHaveCount(1)
    await settings.click()
    await expect(drawer).toBeVisible()
    const drawerBounds = await drawer.boundingBox()
    expect(Math.round(drawerBounds.x + drawerBounds.width)).toBe(width)
    expect(Math.round(drawerBounds.y + drawerBounds.height)).toBe(900)
    if (width === 390) expect(Math.round(drawerBounds.width)).toBe(width)
    await expect(extrema).toBeChecked()
    await expect(nine).not.toBeChecked()
    await nine.check()
    const extremaCount = await stage.getAttribute('data-extrema-count')
    await pure.check()
    await expect(nine).toBeDisabled()
    await expect(stage).toHaveAttribute('data-extrema-count', extremaCount)
    await expect(stage).toHaveAttribute('data-nine-turn-count', '0')
    await drawer.getByRole('button', { name: '完成' }).click()
    await expect(stage).toHaveAttribute('data-pure-mode', 'true')
    await expect(stage.locator('[data-action-id]')).toHaveCount(0)
    await expect(stage.locator('.newow-product-chart-stage__auxiliary-toolbar')).toBeHidden()
    const nativeRows = stage.locator('tr').filter({ has: page.locator('td:nth-child(3)') })
    await expect(nativeRows).toHaveCount(2)
    await settings.click()
    await pure.uncheck()
    await expect(nine).toBeChecked()
    await actions.uncheck()
    await expect(stage.locator('[data-action-id]')).toHaveCount(0)
    await actions.check()
    await page.keyboard.press('Escape')
    await expect(drawer).not.toBeVisible()
    await expect(settings).toBeFocused()
    await settings.click()
    await page.mouse.click(4, 4)
    await expect(drawer).not.toBeVisible()
    await expect(stage.locator('[data-action-id]').first()).toHaveAttribute('data-action-id', id)
    await page.getByRole('tab', { name: '双策略', exact: true }).click()
    await expect(stage).toHaveAttribute('data-comparison-active', 'true')
    expect(productRequests(fixture, 'chart').filter(item => item.strategy === 'oscillation')).toHaveLength(1)
    const osc = stage.locator('[data-origin-strategy="oscillation"]').first()
    await expect(osc).toHaveAttribute('data-action-id', /.+/)
    await settings.click()
    const trendTrack = drawer.getByRole('checkbox', { name: '趋势标记' })
    await trendTrack.uncheck()
    await expect(stage.locator('[data-origin-strategy="trend"]')).toHaveCount(0)
    await expect(osc).toBeVisible()
    await trendTrack.check()
    await drawer.getByRole('checkbox', { name: '背景着色' }).uncheck()
    await drawer.getByRole('button', { name: '简', exact: true }).click()
    await expect(drawer.getByRole('button', { name: '简', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(drawer.getByRole('button', { name: '详', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await drawer.getByRole('button', { name: '完成' }).click()
    await expect(osc.locator('strong')).toHaveText(/^(建仓|清仓) \d+\.\d{2}$/)
    await expect(osc.locator('span')).toHaveCount(0)
    const compactText = await osc.innerText()
    await settings.click()
    await drawer.getByRole('button', { name: '详', exact: true }).click()
    await drawer.getByRole('button', { name: '完成' }).click()
    await expect(osc.locator('span')).toHaveCount(1)
    expect(await osc.innerText()).not.toBe(compactText)
    await page.getByRole('tab', { name: '趋势策略', exact: true }).click()
    await expect(stage).toHaveAttribute('data-comparison-active', 'false')
    await expect(stage.locator('.newow-product-chart-stage__action-callouts:not(.newow-product-chart-stage__dual-tracks) [data-action-id]').first()).toBeVisible()
    await page.getByRole('tab', { name: '双策略', exact: true }).click()
    await expect(stage).toHaveAttribute('data-comparison-active', 'true')
    await page.screenshot({ path: `/private/tmp/newow-ui-nine-dual-${width}.png`, fullPage: false })
    await expect(nativeRows).toHaveCount(3)
    await expect.poll(async () => {
      const auxPane = await nativeRows.nth(1).boundingBox()
      const toolbar = await stage.locator('.newow-product-chart-stage__auxiliary-toolbar').boundingBox()
      return Math.abs(auxPane.y - toolbar.y)
    }).toBeLessThanOrEqual(4)
    await page.getByRole('button', { name: '公式速查', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toContainText('A=MAp(T,7)')
    await dialog.getByRole('combobox', { name: '公式速查主题' }).selectOption('trend_reversal')
    await expect(dialog).toContainText('WR1>97')
    await page.screenshot({ path: `/private/tmp/newow-ui-nine-formula-${width}.png` })
    await page.keyboard.press('Escape')
    const reference = page.getByRole('region', { name: 'Newow 参考与解释', exact: true })
    await reference.scrollIntoViewIfNeeded()
    await reference.getByRole('button', { name: '收益分析 ›' }).click()
    await page.getByRole('dialog', { name: '收益分析' }).getByRole('button', { name: '已完成参考交易' }).click()
    await page.keyboard.press('Escape')
    await expect(reference.locator('article[data-reference-category]')).toHaveCount(2)
    await expect(page.getByRole('button', { name: '全部', exact: true })).toBeVisible()
    await page.screenshot({ path: `/private/tmp/newow-ui-nine-reference-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    assertNoUnexpectedRequests(fixture)
  })
}

test('incompatible companion fails closed while single-strategy facts remain readable', async ({ page }) => {
  const fixture = await installNewowProductFixtures(page)
  await page.goto(newowRoute())
  const stage = page.getByTestId('newow-product-chart-stage')
  await expect(stage).toHaveAttribute('data-auxiliary-state', 'ready')
  await stage.getByRole('button', { name: '双策略对照', exact: true }).click()
  await expect(page.getByText('两策略的窗口、时间或物理合约事实无法对齐，已停止叠加。')).toBeVisible()
  await expect(stage).toHaveAttribute('data-comparison-active', 'false')
  await expect(stage.locator('[data-action-id]').first()).toBeVisible()
  assertNoUnexpectedRequests(fixture)
})

test('detail navigation owns the period selector and preserves daily-weekly navigation', async ({ page }) => {
  const fixture = await installNewowProductFixtures(page, { weeklyCandidate: true })
  await page.goto(newowRoute())
  const row = page.locator('.detail-view-nav').getByRole('group', { name: '周期', exact: true })
  await expect(row).toBeVisible()
  await expect(row.getByRole('button', { name: '日线', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await row.getByRole('button', { name: '周线', exact: true }).click()
  await expect(page.getByTestId('newow-product-chart-stage')).toHaveAttribute('data-frequency', '1w')
  await expect(row.getByRole('button', { name: '周线', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await row.getByRole('button', { name: '日线', exact: true }).click()
  await expect(page.getByTestId('newow-product-chart-stage')).toHaveAttribute('data-frequency', '1d')
  assertNoUnexpectedRequests(fixture)
})
