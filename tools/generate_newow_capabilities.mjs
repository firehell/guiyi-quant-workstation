import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(root, 'services/quant-api/app/market_data/newow/capability_contracts.json')
const target = resolve(root, 'apps/quant-web/src/generated/newowCapabilityContracts.ts')
if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Unknown argument')
const contracts = JSON.parse(readFileSync(source, 'utf8'))
for (const [version, contract] of Object.entries(contracts)) {
  if (!/^newow_product_capabilities_v\d+$/.test(version) || contract.response?.schema_version !== version) {
    throw new Error('Invalid capability contract identity')
  }
}
const entries = Object.entries(contracts).map(([version, contract]) => `  ${JSON.stringify(version)}: ${JSON.stringify(contract)}`).join(',\n')
const output = `// Generated by tools/generate_newow_capabilities.mjs; edit app/market_data/newow/capability_contracts.json.
export interface CapabilityContract {
  readonly response: Readonly<Record<string, unknown>>
  readonly intradayScope?: { readonly allowed: readonly string[]; readonly single: boolean }
}
const contracts = new Map<string, CapabilityContract>(Object.entries({
${entries}
}))
export function capabilityContract(version: string): CapabilityContract | undefined { return contracts.get(version) }
`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Generated capability contracts are stale')
  console.log('Capability contracts are current')
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, output)
  console.log('Generated capability contracts')
}
